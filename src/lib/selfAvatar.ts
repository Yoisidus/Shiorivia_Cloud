/** Presentation-only self avatar data. No arbitrary URLs or SVG uploads. */
export const SELF_AVATAR_PRESETS = ["star", "moon", "sun", "compass", "sparkles", "heart"] as const;
export type SelfAvatarPreset = typeof SELF_AVATAR_PRESETS[number];
export type SelfAvatarChoice = { avatarPreset?: SelfAvatarPreset; avatarImage?: string };
export const SELF_AVATAR_UPLOAD_ENABLED = false;

export function parseSelfAvatar(input: SelfAvatarChoice | Record<string, unknown> | null | undefined): SelfAvatarChoice {
  const preset = input?.avatarPreset;
  const avatarPreset = SELF_AVATAR_PRESETS.find(value => value === preset) || "star";
  const image = input?.avatarImage;
  // Local accepts only bounded raster data generated by the avatar picker.
  // Cloud deliberately drops local-only images, including imported JSON.
  const avatarImage = SELF_AVATAR_UPLOAD_ENABLED && typeof image === "string" &&
    image.length <= 180000 && /^data:image\/jpeg;base64,\/9j\/[A-Za-z0-9+/]+={0,2}$/.test(image) ? image : undefined;
  return { avatarPreset, ...(avatarImage ? { avatarImage } : {}) };
}
